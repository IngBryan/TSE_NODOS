CREATE TABLE persona (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_documento    VARCHAR(8)   NOT NULL UNIQUE,
    nombre1          VARCHAR(60)  NOT NULL,
    nombre2          VARCHAR(60),
    primer_apellido  VARCHAR(60)  NOT NULL,
    segundo_apellido VARCHAR(60),
    fecha_nacimiento DATE         NOT NULL,
    sexo             INTEGER      NOT NULL CHECK (sexo IN (1, 2)),
    cod_nacionalidad INTEGER      NOT NULL CHECK (cod_nacionalidad BETWEEN 1 AND 3),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Organismos autorizados a consumir la PDI. La clave se guarda como hash BCrypt.
CREATE TABLE organismo (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     VARCHAR(40)   NOT NULL UNIQUE,
    nombre     VARCHAR(120)  NOT NULL,
    clave_hash VARCHAR(100)  NOT NULL,
    activo     BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Registro de consultas (Ley 18.331). El id es el idRespuesta del contrato DNIC.
CREATE TABLE consulta (
    id               INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organismo_codigo VARCHAR(40),
    nro_documento    VARCHAR(40),
    id_solicitud     INTEGER      NOT NULL,
    resultado        VARCHAR(40)  NOT NULL,
    correlation_id   VARCHAR(64),
    fecha            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_consulta_fecha ON consulta (fecha);
CREATE INDEX idx_consulta_nro_documento ON consulta (nro_documento);
